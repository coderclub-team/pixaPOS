export const INDIA = { country: "IN", currency: "INR", timezone: "Asia/Kolkata" } as const;

export function countryName(code: string, locale = "en"): string {
  try {
    const names = new Intl.DisplayNames([locale], { type: "region" });
    return names.of(code) ?? code;
  } catch {
    return code;
  }
}

export function countryOptions(): { value: string; label: string }[] {
  return REGION_CODES.map((code) => ({ value: code, label: countryName(code) })).sort((a, b) =>
    a.label.localeCompare(b.label),
  );
}

export function timeZoneOptions(): { value: string; label: string }[] {
  let zones: string[];
  try {
    zones =
      typeof Intl.supportedValuesOf === "function"
        ? Intl.supportedValuesOf("timeZone")
        : FALLBACK_TIMEZONES;
  } catch {
    zones = FALLBACK_TIMEZONES;
  }
  if (!zones.includes(INDIA.timezone)) zones = [INDIA.timezone, ...zones];
  return zones.map((z) => ({ value: z, label: z.replace(/_/g, " ") }));
}

export function currencyOptions(): { value: string; label: string }[] {
  return CURRENCIES.map((c) => ({ value: c, label: c }));
}

/**
 * India-only gate (server + client share it). Returns an error message when
 * the selection leaves the supported market, null when fine.
 */
export function indiaLockError(country: string, currency: string, timezone: string): string | null {
  if (country !== INDIA.country || currency !== INDIA.currency || timezone !== INDIA.timezone) {
    return "We only onboard Indian businesses yet — country India, currency INR, timezone Asia/Kolkata";
  }
  return null;
}
