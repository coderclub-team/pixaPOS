export const seedMenuItems: MenuItem[] = (() => {
  const items: MenuItem[] = [];
  let n = 0;
  CATS.forEach((c, ci) => {
    const catId = `mc_${String(ci + 1).padStart(3, "0")}`;
    c.dishes.forEach((d, di) => {
      n += 1;
      const [name, veg, price, spec] = d;
      const id = `mi_${String(n).padStart(3, "0")}`;
      const img = c.imgs[di % c.imgs.length];
      const multi = !!spec && spec.split("/").length > 1;
      items.push({
        id,
        name,
        slug: slugify(name),
        category_id: catId,
        category_name: c.name,
        description: `${name} — house favourite from ${c.name}`,
        item_type: "service",
        product_type: multi ? "variant" : "simple",
        veg_type: veg,
        taxable: true,
        tax_type: "GST",
        tax_percent: 5,
        hsn_code: "996331",
        images: [{ url: img, sort_order: 0 }],
        image_urls: [img],
        available_channels: ["dine_in", "pickup", "delivery"],
        modifier_group_ids: [],
        variants: buildVariants(id, n, spec, price),
        is_active: true,
        created_at: now,
        updated_at: now,
      });
    });
  });
  // Dev linkage so the KDS recipe dialog has a real card to show: the
  // inventory seed recipe rec_001 (Chicken Biryani) covers both variants.
  for (const item of items) {
    if (item.name === "Chicken Dum Biryani") {
      for (const v of item.variants) v.recipe_id = "rec_001";
    }
  }
  return items;
})();
