function slugify(s: string) {
  return s
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function buildVariants(
  itemId: string,
  itemNo: number,
  spec: string | undefined,
  basePrice: number,
): MenuItemVariant[] {
  if (!spec) {
    return [
      {
        id: `mv_${String(itemNo).padStart(3, "0")}_1`,
        menu_item_id: itemId,
        name: "Regular",
        sku: `S${String(itemNo).padStart(3, "0")}-REG`,
        selling_price: basePrice,
        is_default: true,
        is_active: true,
      },
    ];
  }
  return spec.split("/").map((part, i) => {
    const [vname, vprice] = part.split(":");
    return {
      id: `mv_${String(itemNo).padStart(3, "0")}_${i + 1}`,
      menu_item_id: itemId,
      name: vname,
      sku: `S${String(itemNo).padStart(3, "0")}-V${i + 1}`,
      selling_price: Number(vprice),
      is_default: i === 0,
      is_active: true,
    };
  });
}

